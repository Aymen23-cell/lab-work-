def analyze_sentence():
    sentence = input("Enter a sentence: ").strip()

    words_list = sentence.split()
    total_words = len(words_list)
    total_chars = len(sentence)  # includes spaces

    # Longest and shortest words
    if total_words > 0:
        longest_word = max(words_list, key=len)
        shortest_word = min(words_list, key=len)
    else:
        longest_word = shortest_word = "None"

    # Count vowels (a, e, i, o, u)
    vowels = "aeiouAEIOU"
    vowel_count = sum(1 for char in sentence if char in vowels)

    # Unique words using a set
    unique_words = set(words_list)

    # Words in alphabetical order
    sorted_words = sorted(words_list, key=str.lower)

    # Display on screen
    print("\n--- SENTENCE ANALYSIS REPORT ---")
    print(f"1. Total Words: {total_words}")
    print(f"2. Total Characters: {total_chars}")
    print(f"3. Longest Word: {longest_word}")
    print(f"4. Shortest Word: {shortest_word}")
    print(f"5. Vowel Count: {vowel_count}")
    print(f"6. Unique Words (Set): {unique_words}")
    print(f"7. Alphabetical Order: {sorted_words}")

    # Save report to file
    report = f"""--- SENTENCE ANALYSIS ---
Sentence: "{sentence}"
1. Total Words: {total_words}
2. Total Characters: {total_chars}
3. Longest Word: {longest_word}
4. Shortest Word: {shortest_word}
5. Vowel Count: {vowel_count}
6. Unique Words: {list(unique_words)}
7. Alphabetical Order: {sorted_words}
"""
    with open("word_analysis.txt", "w") as f:
        f.write(report)
    print("\n Analysis successfully saved to 'word_analysis.txt'.")


if __name__ == "__main__":
    analyze_sentence()

def calculate_bill_details(products):
    gross_bill = 0
    detailed_items = []
    most_expensive = products[0]

    for prod in products:
        item_total = prod["price"] * prod["quantity"]
        gross_bill += item_total

        # Track the most expensive product based on unit price
        if prod["price"] > most_expensive["price"]:
            most_expensive = prod

        detailed_items.append(
            {
                "name": prod["name"],
                "price": prod["price"],
                "quantity": prod["quantity"],
                "total": item_total,
            }
        )

    # Apply 10% discount if bill > Rs. 10,000
    discount = 0
    if gross_bill > 10000:
        discount = gross_bill * 0.10

    final_bill = gross_bill - discount
    return detailed_items, gross_bill, discount, final_bill, most_expensive


def shopping_system():
    products = []
    print("--- ENTER 5 PRODUCTS ---")
    for i in range(1, 6):
        print(f"\nProduct {i}:")
        name = input("  Product Name: ")
        price = float(input("  Price (Rs.): "))
        quantity = int(input("  Quantity: "))
        products.append({"name": name, "price": price, "quantity": quantity})

    items, gross, discount, final, expensive = calculate_bill_details(products)

    # Build output bill format
    bill_text = "========== SHOPPING BILL RECEIPT ==========\n"
    for item in items:
        line = f"• {item['name']} | Rs. {item['price']} x {item['quantity']} = Rs. {item['total']}\n"
        bill_text += line
        print(line.strip())

    bill_text += f"-------------------------------------------\n"
    bill_text += f"Gross Total: Rs. {gross:.2f}\n"
    if discount > 0:
        bill_text += f"Discount (10%): -Rs. {discount:.2f}\n"
    bill_text += f"Final Bill: Rs. {final:.2f}\n"
    bill_text += f"Most Expensive Product: {expensive['name']} (Rs. {expensive['price']})\n"
    bill_text += f"===========================================\n"

    print("-" * 45)
    print(f"Gross Total: Rs. {gross:.2f}")
    if discount > 0:
        print(f"Discount Applied: -Rs. {discount:.2f}")
    print(f"Final Bill: Rs. {final:.2f}")
    print(
        f"Most Expensive Item: {expensive['name']} (Rs. {expensive['price']})"
    )

    # Save to file
    with open("bill.txt", "w") as f:
        f.write(bill_text)
    print("\n Bill successfully saved to 'bill.txt'.")


if __name__ == "__main__":
    shopping_system()

# Separate calculation functions
def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b


def divide(a, b):
    if b == 0:
        return "Error! Division by zero."
    return a / b


def modulus(a, b):
    if b == 0:
        return "Error! Modulus by zero."
    return a % b


def calculator():
    while True:
        print("\n--- PYTHON CALCULATOR ---")
        try:
            num1 = float(input("Enter first number: "))
            num2 = float(input("Enter second number: "))

            print("Select Operation:")
            print("  + : Addition")
            print("  - : Subtraction")
            print("  * : Multiplication")
            print("  / : Division")
            print("  % : Modulus")

            choice = input("Enter choice (+, -, *, /, %): ").strip()

            # Using if/elif/else to select operation
            if choice == "+":
                result = add(num1, num2)
            elif choice == "-":
                result = subtract(num1, num2)
            elif choice == "*":
                result = multiply(num1, num2)
            elif choice == "/":
                result = divide(num1, num2)
            elif choice == "%":
                result = modulus(num1, num2)
            else:
                result = "Invalid operation choice!"

            print(f"Result: {result}")

        except ValueError:
            print("Invalid input! Please enter numbers only.")

        # Ask to continue
        again = (
            input("\nDo you want to perform another calculation? (y/n): ")
            .strip()
            .lower()
        )
        if again != "y":
            print("Exiting calculator. Have a great day!")
            break


